//! Lifecycle and launcher cleanup tests: delete and rename remove exported
//! launchers (fail-soft), rename rewrites the display name and last-used
//! setting and moves the MangoHud companion, and saves succeed with a
//! warning when metadata is disabled.

use std::fs;
use std::path::Path;

use crosshook_core::export::{check_launcher_exists, LauncherInfo};
use crosshook_core::profile::{GameProfile, LaunchSection};
use crosshook_core::settings::AppSettingsData;

use super::helpers::{steam_profile, Harness, Metadata};
use crate::services::profiles::launcher_cleanup::cleanup_launchers_for_profile_delete;
use crate::services::profiles::CommitWarning;
use crate::{AppEvent, ProfileChangeReason};

fn changed(reason: ProfileChangeReason, name: &str) -> AppEvent {
    AppEvent::ProfilesChanged {
        reason,
        names: vec![name.to_string()],
    }
}

fn home(harness: &Harness) -> String {
    harness.root.path().to_string_lossy().into_owned()
}

/// Writes CrossHook-watermarked launcher files where `profile` exports them.
fn export_launcher(home: &str, profile: &GameProfile) -> LauncherInfo {
    let info = check_launcher_exists(
        &profile.steam.launcher.display_name,
        &profile.steam.app_id,
        &profile.trainer.path,
        home,
        &format!("{home}/.local/share/Steam"),
    )
    .unwrap();
    for path in [&info.script_path, &info.desktop_entry_path] {
        fs::create_dir_all(Path::new(path).parent().unwrap()).unwrap();
    }
    fs::write(
        &info.script_path,
        "#!/usr/bin/env bash\n# Generated by CrossHook\n",
    )
    .unwrap();
    fs::write(
        &info.desktop_entry_path,
        "[Desktop Entry]\nName=Test Game - Trainer\nComment=Generated by CrossHook\n",
    )
    .unwrap();
    info
}

fn launcher_removed(info: &LauncherInfo) -> bool {
    !Path::new(&info.script_path).exists() && !Path::new(&info.desktop_entry_path).exists()
}

#[test]
fn cleanup_launchers_for_profile_delete_uses_derived_steam_paths() {
    let temp = tempfile::tempdir().unwrap();
    let home = temp.path().to_string_lossy().into_owned();
    let profile = steam_profile(&home);
    let info = export_launcher(&home, &profile);

    let result = cleanup_launchers_for_profile_delete("test-profile", &profile).unwrap();

    assert!(result.is_some());
    assert!(launcher_removed(&info));
}

#[test]
fn cleanup_launchers_for_profile_delete_skips_native_profiles() {
    let profile = GameProfile {
        launch: LaunchSection {
            method: "native".to_string(),
            ..Default::default()
        },
        ..GameProfile::default()
    };

    let result = cleanup_launchers_for_profile_delete("native-profile", &profile).unwrap();

    assert!(result.is_none());
}

#[tokio::test]
async fn delete_removes_exported_launcher_and_publishes_deleted() {
    let mut harness = Harness::new(Metadata::Enabled);
    let profile = steam_profile(&home(&harness));
    harness.profiles.save("Alpha", &profile).unwrap();
    let info = export_launcher(&home(&harness), &profile);

    harness.writer.delete("Alpha".to_string()).await.unwrap();

    assert!(!harness.profiles.profile_exists("Alpha"));
    assert!(launcher_removed(&info));
    assert_eq!(
        harness.next_event().await,
        Some(changed(ProfileChangeReason::Deleted, "Alpha"))
    );
    assert_eq!(harness.next_event().await, None);
}

#[tokio::test]
async fn delete_succeeds_when_launcher_cleanup_cannot_load_the_profile() {
    let mut harness = Harness::new(Metadata::Enabled);
    fs::create_dir_all(&harness.profiles.base_path).unwrap();
    fs::write(
        harness.profiles.base_path.join("Broken.toml"),
        "not = [valid",
    )
    .unwrap();

    harness.writer.delete("Broken".to_string()).await.unwrap();

    assert!(!harness.profiles.profile_exists("Broken"));
    assert_eq!(
        harness.next_event().await,
        Some(changed(ProfileChangeReason::Deleted, "Broken"))
    );
}

#[tokio::test]
async fn rename_cleans_launcher_and_moves_display_name_setting_and_companion() {
    let mut harness = Harness::new(Metadata::Enabled);
    let mut profile = steam_profile(&home(&harness));
    profile.launch.mangohud.enabled = true;
    harness.profiles.save("Alpha", &profile).unwrap();
    let info = export_launcher(&home(&harness), &profile);
    harness
        .settings
        .save(&AppSettingsData {
            last_used_profile: "Alpha".to_string(),
            ..AppSettingsData::default()
        })
        .unwrap();

    let had_launcher = harness
        .writer
        .rename("Alpha".to_string(), "Beta".to_string())
        .await
        .unwrap()
        .into_output();

    assert!(had_launcher);
    assert!(launcher_removed(&info));
    assert!(!harness.profiles.profile_exists("Alpha"));
    let renamed = harness.profiles.load("Beta").unwrap();
    assert_eq!(renamed.steam.launcher.display_name, "Beta");
    assert_eq!(harness.settings.load().unwrap().last_used_profile, "Beta");
    let base = &harness.profiles.base_path;
    assert!(base.join("Beta.mangohud.conf").exists());
    assert!(!base.join("Alpha.mangohud.conf").exists());
    assert_eq!(
        harness.next_event().await,
        Some(changed(
            ProfileChangeReason::Renamed {
                from: "Alpha".to_string()
            },
            "Beta"
        ))
    );
    assert_eq!(harness.next_event().await, None, "rename publishes once");
}

#[tokio::test]
async fn rename_without_exported_launcher_reports_none_and_keeps_other_last_used() {
    let harness = Harness::new(Metadata::Enabled);
    harness
        .profiles
        .save("Alpha", &steam_profile(&home(&harness)))
        .unwrap();
    harness
        .settings
        .save(&AppSettingsData {
            last_used_profile: "Other".to_string(),
            ..AppSettingsData::default()
        })
        .unwrap();

    let had_launcher = harness
        .writer
        .rename("Alpha".to_string(), "Beta".to_string())
        .await
        .unwrap()
        .into_output();

    assert!(!had_launcher);
    assert_eq!(harness.settings.load().unwrap().last_used_profile, "Other");
}

#[tokio::test]
async fn rename_to_same_name_is_a_silent_no_op() {
    let mut harness = Harness::new(Metadata::Enabled);
    let profile = steam_profile(&home(&harness));
    harness.profiles.save("Alpha", &profile).unwrap();
    let info = export_launcher(&home(&harness), &profile);

    let had_launcher = harness
        .writer
        .rename("Alpha".to_string(), " Alpha ".to_string())
        .await
        .unwrap()
        .into_output();

    assert!(!had_launcher);
    assert!(!launcher_removed(&info), "no-op rename keeps launchers");
    assert_eq!(harness.next_event().await, None);
}

#[tokio::test]
async fn save_with_disabled_metadata_succeeds_with_warning() {
    let mut harness = Harness::new(Metadata::Disabled);

    let commit = harness
        .writer
        .save("Alpha".to_string(), steam_profile(&home(&harness)))
        .await
        .unwrap();

    assert_eq!(commit.warnings, vec![CommitWarning::MetadataUnavailable]);
    assert!(harness.profiles.profile_exists("Alpha"));
    assert_eq!(
        harness.next_event().await,
        Some(changed(ProfileChangeReason::Saved, "Alpha"))
    );
}

#[tokio::test]
async fn save_rejects_invalid_runtime_steam_app_id_without_writing() {
    let mut harness = Harness::new(Metadata::Enabled);
    let mut profile = steam_profile(&home(&harness));
    profile.runtime.steam_app_id = "not-a-number".to_string();

    let error = harness
        .writer
        .save("Alpha".to_string(), profile)
        .await
        .unwrap_err();

    assert!(error.message().contains("Invalid Steam App ID"));
    assert!(!harness.profiles.profile_exists("Alpha"));
    assert_eq!(harness.next_event().await, None);
}

#[tokio::test]
async fn export_toml_rejects_names_that_would_inject_header_lines() {
    let harness = Harness::new(Metadata::Disabled);

    let error = harness
        .writer
        .export_toml(
            "Alpha\n[game]".to_string(),
            steam_profile(&home(&harness)),
            false,
        )
        .await
        .unwrap_err();

    assert!(matches!(
        error.kind(),
        crate::AppErrorKind::Validation { field: "profile" }
    ));
}
